// scripts/build-theme.cjs
// Regenerates src/theme.css (light / dark theme) from Tailwind's palette.
// Run after upgrading Tailwind or changing the mappings:  node scripts/build-theme.cjs
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const css = fs.readFileSync(path.join(root, 'node_modules/tailwindcss/theme.css'), 'utf8');
const val = (name) => {
  const m = css.match(new RegExp(`--color-${name}:\\s*([^;]+);`));
  if (!m) throw new Error(`Tailwind colour not found: ${name}`);
  return m[1].trim();
};

const steps = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
// Neutral scale: page and inputs light grey, cards white, borders soft, text dark.
const slateMap = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 500, 600: 500, 700: 300, 800: 200, 900: 'white', 950: 100 };
// Accent scales: pale tints become deep shades so text stays readable on white.
const accentMap = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 700, 500: 600, 600: 600, 700: 700, 800: 200, 900: 100, 950: 50 };
const accents = ['teal', 'cyan', 'emerald', 'amber', 'rose', 'violet', 'sky', 'fuchsia'];

const light = [];
const dark = [];
for (const s of steps) {
  const t = slateMap[s];
  light.push(`  --color-slate-${s}: ${t === 'white' ? '#fff' : val(`slate-${t}`)};`);
  dark.push(`  --color-slate-${s}: ${val(`slate-${s}`)};`);
}
for (const h of accents) {
  for (const s of steps) {
    light.push(`  --color-${h}-${s}: ${val(`${h}-${accentMap[s]}`)};`);
    dark.push(`  --color-${h}-${s}: ${val(`${h}-${s}`)};`);
  }
}
light.push(`  --color-white: ${val('slate-900')};`);
dark.push('  --color-white: #fff;');

const out = `/* SeaScan light / dark theme - GENERATED by scripts/build-theme.cjs from Tailwind's palette. */
/* The app is written with dark-theme classes (bg-slate-950, text-white, text-teal-300...).
   Light mode re-points those palette variables: page and inputs light grey, cards white,
   text dark, accents deeper. data-theme="dark" on an element keeps that area dark in
   light mode (home hero, login header, 3D viewer). */

:root {
  color-scheme: dark;
}

[data-theme="light"] {
  color-scheme: light;
${light.join('\n')}
}

[data-theme="light"] [data-theme="dark"] {
  color-scheme: dark;
${dark.join('\n')}
}
`;

fs.writeFileSync(path.join(root, 'src/theme.css'), out);
console.log('src/theme.css written');
